#!/usr/bin/env python3
"""Regenerates MarketDataJson.kt from madurai_rates.json (run after updating the dataset)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "madurai_rates.json")
out = os.path.join(here, "..", "src", "commonMain", "kotlin", "com", "hark", "sothudiary", "data", "market", "MarketDataJson.kt")
text = json.dumps(json.load(open(src, encoding="utf-8")), ensure_ascii=True, separators=(",", ":"))
def esc(s): return s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
chunks = [text[i:i + 6000] for i in range(0, len(text), 6000)]
with open(out, "w", encoding="utf-8") as f:
    f.write("package com.hark.sothudiary.data.market\n\n")
    f.write("// GENERATED by composeApp/data/gen_market_kt.py from madurai_rates.json – do not edit by hand.\n")
    f.write("internal object MarketDataJson {\n")
    for i, c in enumerate(chunks):
        f.write(f'    private const val P{i} = "{esc(c)}"\n')
    f.write("    fun text(): String = StringBuilder()" + "".join(f".append(P{i})" for i in range(len(chunks))) + ".toString()\n}\n")
print(len(text), "chars in", len(chunks), "chunks ->", out)
